"""Template rendering: `{{key}}` in docs/src/*.md.in is replaced by a value read from the
artifacts (see `values`). An unknown key is an error, so a stale doc cannot be generated."""

from __future__ import annotations

import re
from pathlib import Path

from smartcycle.report.results import _ablation, _speed_delta, render_results

KEY_RE = re.compile(r"\{\{\s*([A-Za-z0-9_.\-]+)\s*\}\}")
# template name -> output path (relative to the repo root)
TARGETS = {"README.md.in": "README.md"}


def _fmt(v) -> str:
    if isinstance(v, bool):
        return str(v).lower()
    if isinstance(v, float):
        return f"{v:.3f}"
    return str(v)


def _flatten(prefix: str, obj, out: dict) -> None:
    if isinstance(obj, dict):
        for k, v in obj.items():
            _flatten(f"{prefix}.{k}" if prefix else str(k), v, out)
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            _flatten(f"{prefix}.{i}", v, out)
    elif obj is not None:
        out[prefix] = _fmt(obj)


def values(art: dict) -> dict[str, str]:
    """Every scalar of every artifact as `<artifact>.<path>` (floats with 3 decimals), plus a
    few derived keys (`derived.*`)."""
    out: dict[str, str] = {}
    for name, obj in art.items():
        if obj is not None:
            _flatten(name, obj, out)
    m, ins, ds = art["metrics"], art.get("insample"), art.get("dataset")
    rf = m["models"]["rf"]
    d = {"rf_speed_delta": f"{_speed_delta(m):+.3f}",
         "km": rf["events"]["distance_km"],
         "fa_per_km_pothole": f"{rf['events']['Pothole']['false_alarms_per_km']:.1f}",
         "fa_per_km_irregularity": f"{rf['events']['Irregularity']['false_alarms_per_km']:.1f}",
         "speed_only_macro_f1": _ablation(m, "(i) speed features ONLY")["macro_f1"],
         "two_s_macro_f1": _ablation(m, "(iii) 2 s")["macro_f1"],
         "fixed_axes_macro_f1": _ablation(m, "(ii) invariant+fixed")["macro_f1"],
         "block_s": f"{m['cv_protocol']['block_s']:.0f}",
         "purge_s": f"{m['cv_protocol']['purge_s']:.0f}",
         "fs": f"{m['config']['fs']:.0f}", "window_s": f"{m['config']['window_s']:g}",
         "step_s": f"{m['config']['step_s']:g}",
         "stationary_mps": f"{m['config']['stationary_mps']:g}",
         "n_point_events": sum(rf["events"][c]["n_labelled"] for c in ("Pothole",
                                                                     "Irregularity")),
         "pot_as_irr": rf["confusion"]["counts"][2][3],
         "irr_as_pot": rf["confusion"]["counts"][3][2],
         "rf_minus_rule": m["models"]["rf"]["macro_f1"] - m["models"]["rule"]["macro_f1"],
         "fa_total_rf": sum(rf["events"][c]["false_alarms"] for c in ("Pothole",
                                                                   "Irregularity"))}
    ref = (m.get("event_reference_predictors") or {}).get("whole-ride Irregularity")
    if ref:
        d["ref_irr_detected"] = ref["Irregularity"]["detected_of"]
        d["ref_irr_false_alarms"] = ref["Irregularity"]["false_alarms"]
    if ins:
        d["overfit_gap"] = ins["macro_f1"] - rf["macro_f1"]
    if ds:
        d["total_min"] = f"{ds['total_duration_s'] / 60:.1f}"
        for r in ds["rides"]:
            d[f"ride_{r['ride_id']}_s"] = f"{r['duration_s']:.0f}"
    for k, v in d.items():
        out[f"derived.{k}"] = _fmt(v)
    return out


def render_template(text: str, vals: dict[str, str]) -> str:
    missing = sorted({k for k in KEY_RE.findall(text) if k not in vals})
    if missing:
        raise KeyError(f"unknown template key(s): {', '.join(missing)}")
    return KEY_RE.sub(lambda mo: vals[mo.group(1)], text)


def target_of(template: Path) -> str:
    return TARGETS.get(template.name, f"docs/{template.name[:-3]}")


def render_all(art: dict, root: str | Path = ".") -> dict[str, str]:
    """{output path: content} for RESULTS.md and every docs/src/*.md.in template."""
    root = Path(root)
    vals = values(art)
    header = ("<!-- GENERATED by `python -m smartcycle report` from {src}; numbers come from "
              "the artifacts. Edit the template, not this file. -->\n\n")
    out = {"docs/RESULTS.md": render_results(art)}
    for t in sorted((root / "docs" / "src").glob("*.md.in")):
        body = render_template(t.read_text(encoding="utf-8"), vals)
        out[target_of(t)] = header.format(src=f"docs/src/{t.name}") + body
    return out
