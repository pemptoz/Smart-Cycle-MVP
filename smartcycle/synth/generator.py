"""Write a SYNTHETIC dataset: ride CSVs in mixed Phyphox-like / plan-style layouts,
labels.csv, rides.csv, routes.geojson and MANIFEST.json (provenance = synthetic)."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from smartcycle.synth.routes import ROUTES, Polyline, write_routes
from smartcycle.synth.signals import RideSim, SimParams, simulate_ride

GENERATOR_VERSION = "0.1.0"
EPOCH_BASE_MS = 1_794_816_000_000  # 2026-11-16 08:00:00 UTC (fixed: output is deterministic)

PHYPHOX_COLS = ["Time (s)", "Acceleration with g x (m/s^2)", "Acceleration with g y (m/s^2)",
                "Acceleration with g z (m/s^2)", "Latitude (°)", "Longitude (°)",
                "Horizontal Accuracy (m)", "Speed (m/s)"]
PLAN_COLS = ["Timestamp (ms)", "Accel_X (m/s²)", "Accel_Y (m/s²)", "Accel_Z (m/s²)",
             "Latitude", "Longitude"]


def _layout_phyphox(sim: RideSim) -> pd.DataFrame:
    """Relative seconds; GPS fixes on their own rows (accel columns empty there)."""
    n, g = len(sim.t), sim.gps
    acc = pd.DataFrame({PHYPHOX_COLS[0]: sim.t, PHYPHOX_COLS[1]: sim.acc[:, 0],
                        PHYPHOX_COLS[2]: sim.acc[:, 1], PHYPHOX_COLS[3]: sim.acc[:, 2]})
    for c in PHYPHOX_COLS[4:]:
        acc[c] = np.full(n, np.nan)
    gps = pd.DataFrame({PHYPHOX_COLS[0]: g["t"], PHYPHOX_COLS[4]: g["latitude"],
                        PHYPHOX_COLS[5]: g["longitude"], PHYPHOX_COLS[6]: g["accuracy"],
                        PHYPHOX_COLS[7]: g["speed"]})
    df = pd.concat([acc, gps], ignore_index=True)[PHYPHOX_COLS]
    return df.sort_values(PHYPHOX_COLS[0], kind="stable").reset_index(drop=True)


def _layout_plan(sim: RideSim, start_ms: int) -> pd.DataFrame:
    """Epoch milliseconds; GPS written on the nearest accel row; no accuracy/speed columns."""
    ts = start_ms + np.round(sim.t * 1000).astype("int64")
    df = pd.DataFrame({PLAN_COLS[0]: ts, PLAN_COLS[1]: sim.acc[:, 0],
                       PLAN_COLS[2]: sim.acc[:, 1], PLAN_COLS[3]: sim.acc[:, 2],
                       PLAN_COLS[4]: np.nan, PLAN_COLS[5]: np.nan})
    idx = np.clip(np.searchsorted(sim.t, sim.gps["t"]), 0, len(sim.t) - 1)
    df.loc[idx, PLAN_COLS[4]] = sim.gps["latitude"]
    df.loc[idx, PLAN_COLS[5]] = sim.gps["longitude"]
    return df


def generate(out: str | Path, n_rides: int = 12, seed: int = 0, hard: bool = False,
             minutes: float | None = None) -> dict:
    """Generate the synthetic dataset in `out`. Returns the manifest."""
    out = Path(out)
    (out / "rides").mkdir(parents=True, exist_ok=True)
    master = np.random.default_rng(seed)
    child_seeds = np.random.SeedSequence(seed).spawn(n_rides)
    route_ids = list(ROUTES)
    rides_rows, label_rows = [], []
    for i in range(n_rides):
        rng = np.random.default_rng(child_seeds[i])
        rid = f"syn_{i:02d}"
        mount = "pocket" if master.random() < 0.4 else "handlebar"
        route_id = route_ids[int(master.integers(len(route_ids)))]
        coords = ROUTES[route_id] if master.random() < 0.5 else ROUTES[route_id][::-1]
        fs = float(master.uniform(50.0, 100.0))
        layout = "plan" if i % 3 == 2 else "phyphox"
        semicolon = layout == "phyphox" and i % 3 == 1 and (i // 3) % 2 == 0
        sim = simulate_ride(rng, Polyline(coords), fs, SimParams(
            hard=hard, duration_s=None if minutes is None else minutes * 60.0, mount=mount))
        path = out / "rides" / f"{rid}.csv"
        if layout == "plan":
            start = EPOCH_BASE_MS + seed * 86_400_000 + i * 3_600_000
            _layout_plan(sim, start).to_csv(path, index=False, na_rep="", float_format="%.6f")
        elif semicolon:  # European-locale export: ';' separator and decimal comma
            _layout_phyphox(sim).to_csv(path, index=False, na_rep="", float_format="%.6f",
                                        sep=";", decimal=",")
        else:
            _layout_phyphox(sim).to_csv(path, index=False, na_rep="", float_format="%.6f")
        fmt = f"{layout}{'-semicolon' if semicolon else ''}"
        rides_rows.append({"ride_id": rid, "file": f"rides/{rid}.csv", "mount": mount,
                           "device": f"synthetic-phone-{i % 3}",
                           "notes": f"SYNTHETIC route={route_id} fs={fs:.1f}Hz layout={fmt}"})
        for a, b, lbl in sim.intervals:
            label_rows.append({"ride_id": rid, "t_start_s": round(a, 3), "t_end_s": round(b, 3),
                               "label": lbl})
    pd.DataFrame(rides_rows).to_csv(out / "rides.csv", index=False)
    pd.DataFrame(label_rows).to_csv(out / "labels.csv", index=False)
    write_routes(out / "routes.geojson")
    manifest = {"provenance": "synthetic", "seed": seed, "version": GENERATOR_VERSION,
                "n_rides": n_rides, "hard": hard, "minutes": minutes,
                "note": "Synthetic data generated by smartcycle.synth. Never report as real."}
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=1))
    return manifest
